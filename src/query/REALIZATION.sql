SELECT 
	bftts.SCHEDULE_CODE ,
	bftts.SCHEDULE_DATE,
	bftmp.name AS CABANG,
	bftmd.name AS DERMAGA,
	BFTMSC2.name AS JENIS_PELAYANAN,
	bftms.NAME AS NAMA_KAPAL_REALISASI,
	bftmsc.name AS OPERATOR_REALISASI,
	bftts.PLOTING_DATE AS REALISASI_TIBA_ALUR,
	bftts.DOCKING_DATE AS REALISASI_SANDAR,
	-- bftms2.DOCKING_ON AS RENCANA_SANDAR,
	bftts.OPEN_BOARDING_DATE AS REALISASI_MULAI_PELAYANAN,
	bftts.CLOSE_BOARDING_DATE AS REALISASI_SELESAI_PELAYANAN,
	bftts.CLOSE_RAMP_DOOR_DATE AS REALISASI_TUTUP_RAMPDOOR,
	-- bftms2.CLOSE_RAMPDOOR_ON AS RENCANA_TUTUP_RAMPDOOR,
	bftts.SAIL_DATE AS REALISASI_KEBERANGKATAN
	-- bftms2.SAIL_TIME AS RENCANA_KEBERANGKATAN
FROM DWHBRONZEUSER.BRZ_FERIZY_T_TRX_SCHEDULE bftts 
-- LEFT JOIN DWHBRONZEUSER.BRZ_FERIZY_T_MTR_SCHEDULE bftms2 ON bftms2.SCHEDULE_CODE = bftts.SCHEDULE_CODE 
JOIN DWHBRONZEUSER.BRZ_FERIZY_T_MTR_SHIP bftms ON bftms.id = bftts.SHIP_ID 
JOIN DWHBRONZEUSER.BRZ_FERIZY_T_MTR_PORT bftmp ON bftmp.id = bftts.PORT_ID 
JOIN DWHBRONZEUSER.BRZ_FERIZY_T_MTR_DOCK bftmd ON bftmd.id = bftts.dock_id
JOIN DWHBRONZEUSER.BRZ_FERIZY_T_MTR_SHIP_COMPANY bftmsc ON bftmsc.ID = bftms.SHIP_COMPANY_ID 
JOIN DWHBRONZEUSER.BRZ_FERIZY_T_MTR_SHIP_CLASS bftmsc2 ON bftmsc2.ID = bftms.SHIP_CLASS 
WHERE bftmp.name IN ('MERAK', 'BAKAUHENI', 'KETAPANG', 'GILIMANUK')
    AND (
	    bftts.ploting_date BETWEEN SYSDATE - INTERVAL '30' DAY AND SYSDATE
	    OR TRUNC(bftts.ploting_date) = TRUNC(SYSDATE)
	)
ORDER BY bftts.PLOTING_DATE ASC

